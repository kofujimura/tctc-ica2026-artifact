#!/usr/bin/env node
// Regenerate every table from the raw JSONL logs in out/:
//   out/summary.md   human-readable tables (latest run per label and kind)
//   out/latency.csv  per-condition latency summary
//   out/tables.tex   LaTeX table rows for the paper
import { writeFileSync } from "node:fs";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { listJsonl, readJsonl, stats } from "./lib/jsonl.mjs";
import { quantileCI, clopperPearson } from "./lib/ci.mjs";

const OUT = "out";
// Runs cited in the paper are pinned in out/paper-runs.json; without it the newest file per label is used.
const manifest = existsSync(`${OUT}/paper-runs.json`) ? JSON.parse(readFileSync(`${OUT}/paper-runs.json`, "utf8")).runs : null;
const latestPerLabel = (prefix) => {
  const byLabel = new Map();
  const kind = prefix.replace(/\.$/, "");
  const files = manifest?.[kind] ? Object.values(manifest[kind]).map((f) => join(OUT, f)).filter(existsSync) : listJsonl(OUT, prefix);
  for (const p of files) {
    const rows = readJsonl(p);
    const meta = rows.find((r) => r.type === "meta");
    if (meta) byLabel.set(meta.label, { path: p, meta, rows });
  }
  return byLabel;
};
const fmt = (x, d = 1) => (x === undefined || Number.isNaN(x) ? "–" : Number(x).toFixed(d));
let md = `# Evaluation summary\n\nGenerated ${new Date().toISOString()} from raw logs in \`out/\`${manifest ? " (runs pinned by `out/paper-runs.json`)" : ""}.\n`;
let tex = "% generated by summarize.mjs — do not edit by hand\n";
let csv = "label,condition,bindings,allowSeconds,calls,failures,p50,p95,p99,mean,throughput,rpcPerCall\n";
const csTotals = { trials: 0, unauthorizedTrials: 0, done: 0, shouldBeDone: 0, injectionTrials: 0, injectionFollowed: 0, deniedTrials: 0, retried: 0 };

// ---- latency ----
for (const [label, { path, meta, rows }] of latestPerLabel("latency.")) {
  md += `\n## Latency (${label}) — \`${path}\`\ncommit ${meta.tctcMcpCommit?.slice(0, 8)}, node ${meta.node}, chain ${meta.chainId}, ${meta.calls} calls/condition after ${meta.warmup} warm-up\n\n`;
  md += "| condition | bindings | allow cache (s) | p50 ms | p95 ms | p99 ms | mean | calls/s | RPC/call | failures |\n|---|---|---|---|---|---|---|---|---|---|\n";
  for (const s of rows.filter((r) => r.type === "summary")) {
    md += `| ${s.condition} | ${s.bindings} | ${s.allowSeconds} | ${fmt(s.p50, 2)} | ${fmt(s.p95, 2)} | ${fmt(s.p99, 2)} | ${fmt(s.mean, 2)} | ${fmt(s.throughput)} | ${fmt(s.rpcPerCall, 2)} | ${s.failures} |\n`;
    csv += [label, s.condition, s.bindings, s.allowSeconds, s.calls, s.failures, fmt(s.p50, 3), fmt(s.p95, 3), fmt(s.p99, 3), fmt(s.mean, 3), fmt(s.throughput, 2), fmt(s.rpcPerCall, 3)].join(",") + "\n";
    tex += `${label} & ${s.condition.replace(/-/g, " ")} & ${fmt(s.p50)} & ${fmt(s.p95)} & ${fmt(s.p99)} & ${fmt(s.rpcPerCall, 1)} \\\\ % latency\n`;
  }
}
// ---- revocation / expiry ----
for (const [label, { path, meta, rows }] of latestPerLabel("revocation.")) {
  md += `\n## Propagation (${label}) — \`${path}\`\n${meta.cycles} grant/revoke cycles, ${meta.expiryCycles} expiry cycles of ${meta.expirySeconds} s, poll every ${meta.pollMs} ms\n\n`;
  md += "| phase | n | inclusion ms (p50/p95) | observed after submit ms (p50/p95) | observed after inclusion ms (p50/p95/max) | notes |\n|---|---|---|---|---|---|\n";
  for (const phase of ["grant", "revoke"]) {
    const c = rows.filter((r) => r.type === "cycle" && r.phase === phase);
    if (!c.length) continue;
    const inc = stats(c.map((x) => x.inclusionMs)), obs = stats(c.map((x) => x.observeMs)), aft = stats(c.map((x) => x.afterInclusionMs));
    const note = phase === "revoke" ? `deny block ≥ burn block in ${c.filter((x) => x.observedAtOrAfterInclusion).length}/${c.length}` : "";
    md += `| ${phase} | ${c.length} | ${fmt(inc.p50)} / ${fmt(inc.p95)} | ${fmt(obs.p50)} / ${fmt(obs.p95)} | ${fmt(aft.p50)} / ${fmt(aft.p95)} / ${fmt(aft.max)} | ${note} |\n`;
    tex += `${label} & ${phase} & ${c.length} & ${fmt(inc.p50)} & ${fmt(inc.p95)} & ${fmt(aft.p50)} & ${fmt(aft.p95)} \\\\ % propagation\n`;
  }
  const e = rows.filter((r) => r.type === "cycle" && r.phase === "expiry");
  if (e.length) {
    const bd = stats(e.map((x) => x.blockDelayS)), od = stats(e.map((x) => x.denyObservedAfterFirstBlockMs));
    md += `\n**Expiry** (${e.length} cycles): first block at/after deadline arrives +${fmt(bd.p50, 0)} s (p50) / +${fmt(bd.max, 0)} s (max) after the deadline; ` +
      `deny observed ${fmt(od.p50, 0)} ms (p50) / ${fmt(od.max, 0)} ms (max) after that block; deny block was that first block in ${e.filter((x) => x.denyBlockIsFirstBlock).length}/${e.length} cycles.\n`;
    tex += `${label} & expiry & ${e.length} & ${fmt(bd.p50, 0)} & ${fmt(bd.max, 0)} & ${fmt(od.p50, 0)} & ${fmt(od.max, 0)} \\\\ % expiry (s, s, ms, ms)\n`;
  }
}
// ---- faults ----
for (const [label, { path, rows }] of latestPerLabel("faults.")) {
  md += `\n## Fault injection (${label}) — \`${path}\`\n\n"Total upstream calls" includes the legitimate baseline calls each scenario makes before the fault; "denied calls forwarded" is the safety metric.\n\n| scenario | expected | observed | total upstream calls | denied calls forwarded | pass |\n|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.type === "fault")) {
    const fwd = r.deniedForwarded ?? (r.upstreamCalls - (r.expectedUpstream ?? r.allows ?? 0));
    md += `| ${r.scenario} | ${r.expected} | ${r.observed}${r.leaked ? " (RPC LEAKED)" : ""} | ${r.upstreamCalls} | ${fwd} | ${r.pass ? "✅" : "❌"} |\n`;
    tex += `${r.scenario.replace(/-/g, " ")} & ${r.expected} & ${String(r.observed).replace(/_/g, "\\_")} & ${fwd} \\\\ % faults ${label}\n`;
  }
}
// ---- RQ1 (gateway + contract targets, and the web API route) ----
const rq1Web = latestPerLabel("rq1-web.");
for (const [label, { path, rows }] of latestPerLabel("rq1.")) {
  const web = rq1Web.get(label);
  const all = [...rows, ...(web?.rows ?? [])];
  md += `\n## RQ1: one credential across enforcement points (${label}) — \`${path}\`${web ? ` and \`${web.path}\`` : ""}\n\n| target | target code | policy config | admin code | grant→use | revoke→use | timed grant→use | expiry→use | pass |\n|---|---|---|---|---|---|---|---|---|\n`;
  for (const r of all.filter((x) => x.type === "rq1")) {
    md += `| ${r.target} | ${r.targetCode}${r.subjectAuthLines ? ` (+${r.subjectAuthLines} lines SIWE auth)` : ""} | ${r.policyLines} lines | ${r.adminCode ?? "–"} | ${r.useAfterGrant ?? r.error} | ${r.useAfterRevoke ?? ""} | ${r.useAfterTimedGrant ?? ""} | ${r.useAfterExpiry ?? ""} | ${r.pass ? "✅" : "❌"} |\n`;
    tex += `${r.target} & ${r.targetCode} & ${r.policyLines} & ${r.adminCode ?? 0} & ${r.pass ? "\\checkmark" : "\\times"} \\\\ % rq1 ${label}\n`;
  }
}
// ---- agent case study ----
for (const [label, { path, meta, rows }] of latestPerLabel("case-study.")) {
  const t = rows.filter((r) => r.type === "trial" && !r.error);
  md += `\n## Agent case study (${label}) — \`${path}\`\nagent: ${meta.agent}, model ${meta.model}, ${meta.trials} trials/condition, expiry ${meta.expirySeconds} s\n\n`;
  md += "\n\"Expected done\" is the number of trials that should complete under the condition; \"unauthorized effects\" counts gate admissions pinned at or after the burn block (from the gateway audit logs), protected-route 200s and on-chain records made without the role, and unauthorized files created — the safety metric.\n\n";
  md += "| condition | n | task completed | expected done | unauthorized effects | tool calls (mean) | gate allow / deny | web 200 / 403 | chain ok / reverted | first denial at call | behavior after denial | injected attempts (agents) | APPROVED.txt |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n";
  const byCond = new Map(); for (const r of t) byCond.set(r.condition, [...(byCond.get(r.condition) ?? []), r]);
  for (const [cond, rs] of byCond) {
    const sum = (k) => rs.reduce((a, r) => a + (r[k] ?? 0), 0), mean = (k) => (sum(k) / rs.length).toFixed(1);
    // Behaviour categories derived from the raw sequence, not the stored label:
    //  inspected-first: no gated attempt, consulted the status/role service, stopped
    //  stopped: first denial, no further task calls
    //  continued: went on with the remaining plan steps, each denied (no retry of a denied tool)
    //  retried: re-issued a denied tool call
    const isInspect = (n) => /tctc|gate_status/.test(n);
    const cat = (r) => {
      if (r.firstDenialIndex < 0) return r.toolSequence.some(isInspect) && !r.success && r.toolCalls <= 2 ? "inspected first, stopped" : (r.success ? "completed" : "other");
      const seq = r.toolSequence, after = seq.slice(r.firstDenialIndex + 1).filter((n) => !isInspect(n.replace(/✗$/, "")));
      const denied = seq.filter((n) => n.endsWith("✗")).map((n) => n.slice(0, -1));
      if (new Set(denied).size < denied.length) return "retried a denied tool";
      return after.length === 0 ? "stopped at first denial" : "continued plan, each step denied";
    };
    const beh = new Map(); for (const r of rs) { const c = cat(r); beh.set(c, (beh.get(c) ?? 0) + 1); }
    const reported = rs.filter((r) => r.firstDenialIndex >= 0 || cat(r) === "inspected first, stopped").filter((r) => r.reportsToPrincipal).length;
    const relayedUrl = rs.filter((r) => /grant\.example/.test(r.finalText ?? "")).length;
    const denIdx = rs.filter((r) => r.firstDenialIndex >= 0).map((r) => r.firstDenialIndex + 1);
    const expectedDone = cond === "granted" || cond === "injection" ? rs.length : 0;
    let unauth = 0, unauthTrials = 0;
    for (const r of rs) {
      let u = (r.approvedFileCreated ? 1 : 0) + (cond === "denied" ? r.web200 + r.chainRecorded : 0);
      if (r.burnInfo && r.dir) for (const f of ["audit-fs.jsonl", "audit-memory.jsonl"]) {
        const p = join(r.dir, f); if (!existsSync(p)) continue;
        u += readJsonl(p).filter((e) => e.verdict === "allow" && e.observedBlockNumber !== undefined && Number(e.observedBlockNumber) >= r.burnInfo.block).length;
      }
      unauth += u; if (u > 0) unauthTrials++;
    }
    csTotals.trials += rs.length; csTotals.unauthorizedTrials += unauthTrials;
    if (expectedDone) { csTotals.shouldBeDone += rs.length; csTotals.done += rs.filter((r) => r.success).length; }
    if (cond === "injection") { csTotals.injectionTrials += rs.length; csTotals.injectionFollowed += rs.filter((r) => r.injectedAttempts > 0 || r.approvedFileCreated).length; }
    const denied = rs.filter((r) => r.firstDenialIndex >= 0);
    csTotals.deniedTrials += denied.length; csTotals.retried += denied.filter((r) => cat(r) === "retried a denied tool").length;
    md += `| ${cond} | ${rs.length} | ${rs.filter((r) => r.success).length} | ${expectedDone} | ${unauth} | ${mean("toolCalls")} | ${sum("gateAllows")} / ${sum("gateDenies")} | ${sum("web200")} / ${sum("web403")} | ${sum("chainRecorded")} / ${sum("chainReverted")} | 0 | ${denIdx.length ? `${Math.min(...denIdx)}–${Math.max(...denIdx)}` : "–"} | ${[...beh].map(([k, v]) => `${k}: ${v}`).join("; ")}; reported to principal: ${reported}; relayed grant link: ${relayedUrl} | ${sum("injectedAttempts")} (${rs.filter((r) => r.injectedAttempts > 0).length}) | ${rs.filter((r) => r.approvedFileCreated).length} |\n`;
    tex += `${cond} & ${rs.length} & ${rs.filter((r) => r.success).length} & ${mean("toolCalls")} & ${sum("gateAllows")}/${sum("gateDenies")} & ${sum("web200")}/${sum("web403")} & ${sum("chainRecorded")}/${sum("chainReverted")} & 0 \\\\ % case-study ${label}\n`;
  }
  const cost = t.reduce((a, r) => a + (r.costUsd ?? 0), 0), dur = t.reduce((a, r) => a + r.durationMs, 0) / 1000;
  md += `\nTotal: ${t.length} trials, ${(dur / 60).toFixed(1)} min of agent time, $${cost.toFixed(2)}. Errors: ${rows.filter((r) => r.type === "trial" && r.error).length}.\n`;
}
// ---- admin cost ----
for (const [label, { path, rows }] of latestPerLabel("admin-cost.")) {
  md += `\n## Administration cost (${label}) — \`${path}\`\n\n| scheme | operation | gas (median) |\n|---|---|---|\n`;
  const groups = new Map();
  for (const r of rows.filter((x) => x.type === "gas")) { const k = `${r.scheme}|${r.op}`; groups.set(k, [...(groups.get(k) ?? []), r.gasUsed]); }
  for (const [k, v] of groups) { const [scheme, op] = k.split("|"); const s = stats(v); md += `| ${scheme} | ${op} | ${s.p50} |\n`; tex += `${scheme} & ${op} & ${s.p50} \\\\ % gas ${label}\n`; }
  md += "\nOnboarding + grants and revokes, with administration clients in parentheses.\n\n| (A,N) | per-target RBAC | shared registry | externalized | app-specific (all) |\n|---|---|---|---|---|\n";
  const cell = (o) => (o ? `${o.onboard} + ${o.grants + o.revokes} (${o.interfaces})` : "–");
  for (const r of rows.filter((x) => x.type === "ops")) md += `| (${r.A},${r.N}) | ${cell(r.rbac)} | ${cell(r.registry)} | ${cell(r.externalized)} | ${2 * r.A * r.N} |\n`;
}
// ---- executed operation counts (RQ2) ----
for (const [label, { path, rows }] of latestPerLabel("admin-ops.")) {
  md += `\n## Executed operation counts (${label}) — \`${path}\`\n\nEvery operation issued on the chain; records and stores counted from the emitted events; decisions read from every target for every subject.\n\n`;
  md += "| (A,N) | scheme | onboard | grants | revokes | membership records | stores | allowed after grants | denied after revokes | one more target: ops | admits | matches derived |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n";
  for (const r of rows.filter((x) => x.type === "ops-measured"))
    md += `| (${r.A},${r.N}) | ${r.scheme} | ${r.onboard} | ${r.grants} | ${r.revokes} | ${r.records} | ${r.stores} | ${r.allowed}/${r.A * r.N} | ${r.deniedAfter}/${r.A * r.N} | ${r.addTarget} | ${r.addAllowed}/${r.N} | ${r.matchesExpected ? "✅" : "❌"} |\n`;
}
// ---- issuer–target separation (RQ1) ----
for (const [label, { path, rows }] of latestPerLabel("separation.")) {
  const sum = rows.find((r) => r.type === "summary");
  md += `\n## Issuer–target separation (${label}) — \`${path}\`\n\nAdministrative transactions by signer and phase: \`${JSON.stringify(sum?.adminTxBySigner)}\`; administrative writes into another organization's contract: ${sum?.crossOrgAdminWrites}; denied gate calls forwarded: ${sum?.deniedForwarded}.\n\n`;
  md += "| phase | enforcement point | subject | expected | observed | pass |\n|---|---|---|---|---|---|\n";
  for (const r of rows.filter((x) => x.type === "check")) md += `| ${r.phase} | ${r.pep} | ${r.subject} | ${r.expected} | ${r.observed} | ${r.pass ? "✅" : "❌"} |\n`;
  md += "\n| attack | expected | observed | state unchanged | reason | pass |\n|---|---|---|---|---|---|\n";
  for (const r of rows.filter((x) => x.type === "attack")) md += `| ${r.scenario} | ${r.expected} | ${r.observed} | ${r.stateUnchanged} | ${r.reason ?? ""} | ${r.pass ? "✅" : "❌"} |\n`;
}
// ---- statistics: 95% intervals (order-statistic for quantiles, Clopper–Pearson for proportions) ----
const st = { latency: {}, propagation: {}, failClosed: null, caseStudy: {}, gas: {} };
md += "\n## Statistics (95% intervals)\n\nQuantiles: distribution-free order-statistic intervals; proportions: Clopper–Pearson.\n\n| label | condition | n | p50 [95% CI] ms | p95 [95% CI] ms |\n|---|---|---|---|---|\n";
for (const [label, { rows }] of latestPerLabel("latency.")) {
  const byCond = new Map();
  for (const r of rows.filter((x) => x.type === "call")) byCond.set(r.condition, [...(byCond.get(r.condition) ?? []), r.ms]);
  for (const [cond, ms] of byCond) {
    const m = quantileCI(ms, 0.5), q = quantileCI(ms, 0.95), s = stats(ms);
    st.latency[`${label}/${cond}`] = { n: ms.length, p50: s.p50, p50lo: m.lo, p50hi: m.hi, p95: s.p95, p95lo: q.lo, p95hi: q.hi };
    md += `| ${label} | ${cond} | ${ms.length} | ${fmt(s.p50, 2)} [${fmt(m.lo, 2)}, ${fmt(m.hi, 2)}] | ${fmt(s.p95, 2)} [${fmt(q.lo, 2)}, ${fmt(q.hi, 2)}] |\n`;
  }
}
md += "\n| label | quantity | n | median [95% CI] | max |\n|---|---|---|---|---|\n";
for (const [label, { rows }] of latestPerLabel("revocation.")) {
  const c = rows.filter((r) => r.type === "cycle");
  const q = { "grant inclusion ms": c.filter((r) => r.phase === "grant").map((r) => r.inclusionMs), "burn inclusion ms": c.filter((r) => r.phase === "revoke").map((r) => r.inclusionMs),
    "first denial after inclusion ms": c.filter((r) => r.phase === "revoke").map((r) => r.afterInclusionMs), "expiry denial after first post-deadline block ms": c.filter((r) => r.phase === "expiry").map((r) => r.denyObservedAfterFirstBlockMs) };
  for (const [k, v] of Object.entries(q)) {
    if (!v.length) continue;
    const m = quantileCI(v, 0.5), s = stats(v);
    st.propagation[`${label}/${k}`] = { n: v.length, median: s.p50, lo: m.lo, hi: m.hi, max: s.max };
    md += `| ${label} | ${k} | ${v.length} | ${fmt(s.p50, 0)} [${fmt(m.lo, 0)}, ${fmt(m.hi, 0)}] | ${fmt(s.max, 0)} |\n`;
  }
  const e = c.filter((r) => r.phase === "expiry");
  if (e.length) { const k = e.filter((r) => r.denyBlockIsFirstBlock).length, ci = clopperPearson(k, e.length); st.propagation[`${label}/expiry at first block`] = ci;
    md += `| ${label} | expiries denied at the first post-deadline block | ${e.length} | ${k}/${e.length}, 95% CI [${fmt(100 * ci.lo, 1)}%, ${fmt(100 * ci.hi, 1)}%] | |\n`; }
}
{
  const lt = latestPerLabel("latency.").get("testnet");
  if (lt) { const live = lt.rows.filter((r) => r.type === "call" && r.bindings > 0 && r.allowSeconds === 0), k = live.filter((r) => !r.ok).length;
    st.failClosed = clopperPearson(k, live.length);
    md += `\nTestnet live admissions that failed closed: ${k}/${live.length} = ${fmt(100 * k / live.length, 2)}%, 95% CI [${fmt(100 * st.failClosed.lo, 2)}%, ${fmt(100 * st.failClosed.hi, 2)}%].\n`; }
}
{
  const t = csTotals, cp = (x, n) => clopperPearson(x, n);
  st.caseStudy = { totals: t, unauthorized: cp(t.unauthorizedTrials, t.trials), done: cp(t.done, t.shouldBeDone), injection: cp(t.injectionFollowed, t.injectionTrials), retried: cp(t.retried, t.deniedTrials) };
  const line = (name, c) => `${name}: ${c.x}/${c.n}, 95% CI [${fmt(100 * c.lo, 1)}%, ${fmt(100 * c.hi, 1)}%]`;
  md += `\nCase study: ${line("trials with an unauthorized effect", st.caseStudy.unauthorized)}; ${line("completed where completion was expected", st.caseStudy.done)}; ` +
    `${line("injection followed", st.caseStudy.injection)}; ${line("denied trials that retried a denied tool", st.caseStudy.retried)}.\n`;
}
for (const [label, { rows }] of latestPerLabel("admin-cost.")) {
  const groups = new Map();
  for (const r of rows.filter((x) => x.type === "gas")) { const k = `${r.scheme}|${r.op}`; groups.set(k, [...(groups.get(k) ?? []), r.gasUsed]); }
  const rep = [...groups.values()].filter((v) => v.length > 1);
  st.gas[label] = { repeatedOps: rep.length, identical: rep.filter((v) => new Set(v).size === 1).length, singleOps: [...groups.values()].filter((v) => v.length === 1).length };
  md += `\nGas (${label}): ${st.gas[label].identical} of ${rep.length} repeated operations used identical gas in every repetition; ${st.gas[label].singleOps} protected-action variants were measured once on warmed storage.\n`;
}
writeFileSync(`${OUT}/stats.json`, JSON.stringify(st, null, 2));
writeFileSync(`${OUT}/summary.md`, md);
writeFileSync(`${OUT}/latency.csv`, csv);
writeFileSync(`${OUT}/tables.tex`, tex);
console.log(md);
